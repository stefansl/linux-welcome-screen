#!/bin/bash
# Universal installer for Linux Welcome Screen (multi-shell support)
# Author: Stefan Schulz-Lauterbach
# License: MIT

set -euo pipefail

REPO_URL="https://raw.githubusercontent.com/stefansl/linux-welcome-screen/main"
TARGET="/etc/profile.d/welcome.sh"
TMP_WELCOME="/tmp/welcome.sh"

echo "🔧 Installing Linux Welcome Screen..."

if [ "$EUID" -ne 0 ]; then
    echo "❌ Please run as root (use: sudo bash -c 'curl ... | bash')"
    exit 1
fi

# --- Detect package manager (for figlet) ---
if command -v apt >/dev/null 2>&1; then
    PM_INSTALL="apt-get install -y -qq"; UPDATE_CMD="apt-get update -qq"
elif command -v dnf >/dev/null 2>&1; then
    PM_INSTALL="dnf install -y -q"; UPDATE_CMD="dnf makecache -q"
elif command -v yum >/dev/null 2>&1; then
    PM_INSTALL="yum install -y -q"; UPDATE_CMD="yum makecache -q"
elif command -v zypper >/dev/null 2>&1; then
    PM_INSTALL="zypper install -y -q"; UPDATE_CMD="zypper refresh -q"
elif command -v pacman >/dev/null 2>&1; then
    PM_INSTALL="pacman -S --noconfirm --quiet"; UPDATE_CMD="pacman -Sy --noconfirm --quiet"
elif command -v apk >/dev/null 2>&1; then
    PM_INSTALL="apk add -q"; UPDATE_CMD="apk update -q"
else
    PM_INSTALL=""; UPDATE_CMD=""
fi

# --- Download welcome.sh ---
echo "🌐 Downloading welcome.sh from GitHub..."
curl -fsSL "$REPO_URL/welcome.sh" -o "$TMP_WELCOME"

install -m 755 "$TMP_WELCOME" "$TARGET"
echo "✅ Installed core script at: $TARGET"

# --- Zsh support ---
if command -v zsh >/dev/null 2>&1; then
    ZSH_CONF="/etc/zsh/zlogin"
    if ! grep -q "$TARGET" "$ZSH_CONF" 2>/dev/null; then
        echo "source $TARGET" >> "$ZSH_CONF"
        echo "✅ Linked into Zsh via $ZSH_CONF"
    fi
fi

# --- Fish shell support ---
if command -v fish >/dev/null 2>&1; then
    FISH_CONF_DIR="/etc/fish/conf.d"
    mkdir -p "$FISH_CONF_DIR"
    FISH_FILE="$FISH_CONF_DIR/welcome.fish"
    cat > "$FISH_FILE" <<'EOF'
# Auto-generated by Linux Welcome Screen installer
if status is-interactive
    bash /etc/profile.d/welcome.sh ^/dev/null
end
EOF
    echo "✅ Added Fish shell support at $FISH_FILE"
fi

# Package managers must not read from stdin: with "curl ... | bash" stdin is the
# script itself, and apt/dpkg would swallow the rest of it.
export DEBIAN_FRONTEND=noninteractive

# --- Refresh package index once, only if something needs installing ---
PM_UPDATED=0
pm_update() {
    if [ "$PM_UPDATED" -eq 0 ]; then
        eval "$UPDATE_CMD" </dev/null >/dev/null 2>&1 || true
        PM_UPDATED=1
    fi
}

# --- Install figlet ---
if ! command -v figlet >/dev/null 2>&1 && [ -n "$PM_INSTALL" ]; then
    echo "📦 Installing 'figlet' for ASCII banners..."
    pm_update
    eval "$PM_INSTALL figlet" </dev/null >/dev/null 2>&1 || echo "⚠  Could not install figlet automatically."
fi

# --- Login history (Debian 13+ dropped 'last'; wtmpdb is the replacement) ---
if command -v apt >/dev/null 2>&1 && ! command -v last >/dev/null 2>&1 && ! command -v wtmpdb >/dev/null 2>&1; then
    echo "📦 Installing 'wtmpdb' for the last login display..."
    pm_update
    if eval "$PM_INSTALL wtmpdb libpam-wtmpdb" </dev/null >/dev/null 2>&1; then
        echo "✅ wtmpdb installed (logins are recorded from now on)"
    else
        echo "⚠  Could not install wtmpdb automatically."
    fi
fi

# --- Cleanup ---
rm -f "$TMP_WELCOME"
case "$0" in /tmp/*|/var/tmp/*) rm -- "$0" >/dev/null 2>&1 || true ;; esac

echo
echo "✨ Installation complete!"
echo "📍 Installed to: $TARGET"
echo "💡 Works with: Bash, Zsh, Fish, Ksh, Dash"
echo "💡 Test it with:  bash -l"
